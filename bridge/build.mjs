// Builds src/game.js (the rules the server runs) from the same files the web page loads:
// js/engine.js, js/bidding.js, js/leads.js, js/bots.js, js/ddplay.js and js/table.js. Run automatically by `npm run dev` and `npm run deploy`.
// Also writes js/min/: the page's scripts without comments and spacing (see the end). /* feature: perf8 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = f => readFileSync(join(root, 'js', f), 'utf8')
  // the page's files also work as plain scripts and in Node tests; the server doesn't need those hooks
  .replace(/^if \(typeof require !== 'undefined'.*\n/gm, '')
  .replace(/^if \(typeof module !== 'undefined'[\s\S]*?\n\};?\s*$/gm, '')
  .replace(/^if \(typeof module !== 'undefined'.*\n/gm, '');

const prelude = `// GENERATED by build.mjs from js/engine.js, js/bidding.js, js/leads.js, js/bots.js, js/ddplay.js and js/table.js. Do not edit.
// The server runs the same rules, robots and table actions as the web page.

let me = { id: '', name: '' };
let lastError = null;
const toast = msg => { lastError = msg; };
const rid = n => Array.from({ length: n }, () => 'ABCDEFGHJKLMNPQRSTUVWXYZ'[Math.floor(Math.random() * 24)]).join('');
let T = null; // only the page's own single table uses this; the server always passes the table explicitly
export function setMe(m) { me = { id: m.id || '', name: m.name || '' }; lastError = null; }
export function fail(msg) { toast(msg); return false; }
export function takeError() { const e = lastError; lastError = null; return e; }

`;
const exports = `

export {
  SEATS, SEAT_NAME, A, newTable, startBoard, sysMsg, mySeat, canSee, turnSeat, controllerOf, occupant,
  dummySeat, remainingHand, completedTricks, rid, legalCalls, legalPlays, botCall, botPlay, botPlayH, sureTricks, claimHolds, claimAccept, claimAnswer, claimSolver, claimPos, robotClaimCount, ddView, ddWorthIt, playKey, friendsMode, undoReveals,
};
export { scoreNS, boardVul }; // feature: daily
`;
writeFileSync(join(root, 'src', 'game.js'), prelude + read('engine.js') + '\n' + read('bidding.js') + '\n' + read('leads.js') + '\n' + read('bots.js') + '\n' + read('ddplay.js') + '\n' + read('table.js') + exports);
console.log('built src/game.js');

/* feature: perf8 */
// js/min/<file>.js: the scripts index.html loads (its `js/min/` tags), with comments and spacing removed by
// esbuild (names, statements and strings are kept exactly; each file stays a plain script). About a quarter fewer
// bytes over the network (gzip), so a first visit on a slow phone connection is ready sooner. The source files in
// js/ stay what you edit; the solver workers import the js/min/ copies too (perf10), the tests load js/. GitHub Pages serves the repository as
// it is, so js/min/ is committed: run `node build.mjs` (npm test does too) after editing js/ and commit js/min/.
// `node build.mjs --check` fails when js/min/ is out of date. Without esbuild (no `npm install`) the copies are verbatim.
const minDir = join(root, 'js', 'min');
const pageScripts = [...readFileSync(join(root, 'index.html'), 'utf8').matchAll(/src="js\/min\/([\w.-]+\.js)"/g)].map(m => m[1]);
let esbuild = null;
try { esbuild = await import('esbuild'); } catch (e) { console.warn('build: esbuild not found (run npm install); js/min/ gets verbatim copies'); }
const minify = (f, src) => esbuild
  ? esbuild.transformSync(src, { loader: 'js', minifyWhitespace: true, legalComments: 'none', charset: 'utf8', sourcefile: f }).code
  : src;
mkdirSync(minDir, { recursive: true });
let stale = 0;
for (const f of pageScripts) {
  const out = `// GENERATED by build.mjs from js/${f} (comments and spacing removed). Edit js/${f}, not this file.\n` + minify(f, readFileSync(join(root, 'js', f), 'utf8'));
  const dest = join(minDir, f);
  if (existsSync(dest) && readFileSync(dest, 'utf8') === out) continue;
  stale++;
  if (!process.argv.includes('--check')) writeFileSync(dest, out);
}
for (const f of readdirSync(minDir)) if (!pageScripts.includes(f)) { stale++; if (!process.argv.includes('--check')) unlinkSync(join(minDir, f)); }
if (process.argv.includes('--check')) {
  if (stale) { console.error(`build: js/min/ is out of date (${stale} files): run node build.mjs`); process.exitCode = 1; }
  else console.log('js/min/ up to date');
} else console.log(`built js/min/ (${pageScripts.length} scripts, ${stale} changed)`);
