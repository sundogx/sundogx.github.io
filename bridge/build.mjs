// Builds src/game.js (the rules the server runs) from the same files the web page loads:
// js/engine.js, js/bots.js and js/table.js. Run automatically by `npm run dev` and `npm run deploy`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = f => readFileSync(join(root, 'js', f), 'utf8')
  // the page's files also work as plain scripts and in Node tests; the server doesn't need those hooks
  .replace(/^if \(typeof require !== 'undefined'.*\n/gm, '')
  .replace(/^if \(typeof module !== 'undefined'[\s\S]*?\n\};?\s*$/gm, '')
  .replace(/^if \(typeof module !== 'undefined'.*\n/gm, '');

const prelude = `// GENERATED by build.mjs from js/engine.js, js/bots.js and js/table.js. Do not edit.
// The server runs the same rules, robots and table actions as the web page.

let me = { id: '', name: '' };
let lastError = null;
const toast = msg => { lastError = msg; };
const rid = n => Array.from({ length: n }, () => 'ABCDEFGHJKLMNPQRSTUVWXYZ'[Math.floor(Math.random() * 24)]).join('');
let T = null; // only the page's own single table uses this; the server always passes the table explicitly
export function setMe(m) { me = { id: m.id || '', name: m.name || '' }; lastError = null; }
export function fail(msg) { toast(msg); return false; }
export function takeError() { const e = lastError; lastError = null; return e; }

`;
const exports = `

export {
  SEATS, SEAT_NAME, A, newTable, startBoard, sysMsg, mySeat, canSee, turnSeat, controllerOf, occupant,
  dummySeat, remainingHand, completedTricks, rid, legalCalls, legalPlays, botCall, botPlay, sureTricks,
};
`;
writeFileSync(join(root, 'src', 'game.js'), prelude + read('engine.js') + '\n' + read('bots.js') + '\n' + read('table.js') + exports);
console.log('built src/game.js');
